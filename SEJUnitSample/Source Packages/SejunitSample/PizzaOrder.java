    private void btnPlaceOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPlaceOrderActionPerformed
        String name = txtName.getText();
        
        Object selectedSize = cmbSize.getSelectedItem();
        String size = selectedSize.toString();
        float sizePrice = 0;
        
        Object selectedTopping = cmbTopping.getSelectedItem();
        String topping = selectedTopping.toString();
        float toppingPrice = 0;
        
        Object selectedCrust = cmbCrust.getSelectedItem();
        String crust = selectedCrust.toString();
        float crustPrice = 0;
        
        int quantity = Integer.parseInt(txtQuantity.getText());
        if(quantity == 0 || txtQuantity.getText() == null){
            quantity = 1;
        }
        else{
            quantity = Integer.parseInt(txtQuantity.getText());
        }
        
        // Price Detailes of Pizza Size
        if(size.equals("Small")){
            sizePrice = 200f;
        }
        else if(size.equals("Medium")){
            sizePrice = 350f;
        }
        else if(size.equals("Large")){
            sizePrice = 450f;
        }
        
        // Price Detailes of Topping
        if(topping.equals("Cheese")){
            toppingPrice = 150f;
        }
        else if(topping.equals("Pepperoni")){
            toppingPrice = 120f;
        }
        else if(topping.equals("Mushroom")){
            toppingPrice = 70f;
        }
        else if(topping.equals("Veggie")){
            toppingPrice = 50f;
        }
        else if(topping.equals("Chicken")){
            toppingPrice = 200f;
        }
        
        // Price Detailes of Crust
        if(size.equals("Thin Crust")){
            crustPrice = 50f;
        }
        else if(size.equals("Thick Crust")){
            crustPrice = 40f;
        }
        else if(size.equals("Stuffed Crust")){
            crustPrice = 80f;
        }
        
        float totalPrice = (sizePrice + toppingPrice + crustPrice) * quantity;
        JOptionPane.showMessageDialog(this,"Total Price: " + totalPrice + "\nYour Order Has Been Placed \nYour Name: " + name + "\nPizza Size: " + size + "\nTopping: " + topping + "\nCrust: " + crust);
    }//GEN-LAST:event_btnPlaceOrderActionPerformed

