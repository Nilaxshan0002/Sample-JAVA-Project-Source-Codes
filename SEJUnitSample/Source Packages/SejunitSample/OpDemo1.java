
public class OpDemo1 {
    public static void main(String[] args) {
        
        
        int x = 10;
        int y = 3;
        
        // Addition
        int add = x+ y;
        System.out.println("Addition: " + add);
        
        //Subtraction
        int sub = x- y;
        System.out.println("Subtraction: " + sub);
        
        //Multplication
        int mult = x*y;
        System.out.println("Multiplication: " + mult);
        
        //Modulese
        int mod = x%y;
        System.out.println("Modulese: " + mod);
        
    }
}
