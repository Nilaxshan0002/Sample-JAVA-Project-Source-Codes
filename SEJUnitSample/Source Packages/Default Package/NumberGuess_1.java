    private void btnGuessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuessActionPerformed
        
        if(randomNumber == -1){
            JOptionPane.showMessageDialog(this, "Firt Please Generate A Number.");
            return;
        }
        
        if(guessLeft <= 0){
            JOptionPane.showMessageDialog(this, "No Guesses Left. Please Generate A New Number");
            return;
        }
        
        String generate = txtGuessNumber.getText();
        int guess = Integer.parseInt(generate);
        
        if(guess == randomNumber){
            JOptionPane.showMessageDialog(this, "Yes! Your Guess Is Correct.");
            randomNumber = -1;
        }
        else{
            guessLeft--;
            if(guessLeft == 0){
                JOptionPane.showMessageDialog(this, "Wrong, No Guesses Left, Try Again.\n Right Number Is " + randomNumber);
                txtGuessNumber.setText("");
                randomNumber = -1;
            }
            else{
                txtGuessNumber.setText("");
                if(guess > randomNumber){
                    JOptionPane.showMessageDialog(this, "Wrong! It Less Then " + guess);
                }
                else{
                    JOptionPane.showMessageDialog(this, "Wrong! It Greater Then " + guess);
                }
            }
            lblGuesses.setText("Guesses You Have Left: "+ guessLeft);
            txtGuessNumber.setText("");
        }
    }//GEN-LAST:event_btnGuessActionPerformed

