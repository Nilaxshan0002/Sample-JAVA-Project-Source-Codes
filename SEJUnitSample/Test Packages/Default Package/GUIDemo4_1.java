    private void tableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMouseClicked
        int rowId = table.getSelectedRow();
        
        String regNo = dtm.getValueAt(rowId, 0).toString();
        String name = dtm.getValueAt(rowId, 1).toString();
        String contact = dtm.getValueAt(rowId, 2).toString();
        String batch = dtm.getValueAt(rowId, 3).toString();
        
        txtRegNo.setText(regNo);
        txtName.setText(name);
        txtPhone.setText(contact);
        txtBatch.setText(batch);
    }//GEN-LAST:event_tableMouseClicked

    private void tableKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_tableKeyPressed
        char ch = evt.getKeyChar();
        int i = ch;
        
        if(i == 127){
            int rowId = table.getSelectedRow();
            dtm.removeRow(rowId);
        }
    }//GEN-LAST:event_tableKeyPressed

