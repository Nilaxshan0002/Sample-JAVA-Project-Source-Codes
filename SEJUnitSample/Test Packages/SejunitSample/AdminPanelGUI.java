    private void handleSelection(String option) {
        switch(option) {
            case "1":
                new AddProductGUI().setVisible(true);
                this.dispose();
                break;
            case "2":
                JOptionPane.showMessageDialog(this, "View Products selected");
                break;
            case "3":
                JOptionPane.showMessageDialog(this, "Update Product Price selected");
                break;
            case "4":
                new DeleteProductGUI().setVisible(true);
                this.dispose();
                break;
            case "5":
                JOptionPane.showMessageDialog(this, "Returning to Main Menu");
                this.dispose();
                break;
            default:
                JOptionPane.showMessageDialog(this, "Please select an option (1-5)");
        }
    }
