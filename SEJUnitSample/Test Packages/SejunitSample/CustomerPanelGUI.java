    private void handleSelection(String option) {
        switch(option) {
            case "1":
                JOptionPane.showMessageDialog(this, "Browse Products selected");
                // new BrowseProductsGUI().setVisible(true);
                break;
            case "2":
                JOptionPane.showMessageDialog(this, "Add Product to Order selected");
                // new AddToOrderGUI().setVisible(true);
                break;
            case "3":
                JOptionPane.showMessageDialog(this, "View Current Order selected");
                // new ViewOrderGUI().setVisible(true);
                break;
            case "4":
                JOptionPane.showMessageDialog(this, "Finalize Order selected");
                // new FinalizeOrderGUI().setVisible(true);
                break;
            case "5":
                this.dispose(); // Close current window
                // new MainMenuGUI().setVisible(true);
                break;
            default:
                JOptionPane.showMessageDialog(this, "Please select an option (1-5)");
        }
    }

