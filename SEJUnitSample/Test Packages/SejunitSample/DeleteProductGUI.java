    private void deleteProduct() {
        String name = txtProname.getText();
        String price = txtProprice.getText();
        String quantity = txtProquantity.getText();
        
        // Show confirmation dialog
        int option = javax.swing.JOptionPane.showConfirmDialog(
            this, 
            "Are you sure you want to delete this product?\n\n" +
            "Product Name: " + name + "\n" +
            "Price: " + price + " LKR\n" +
            "Quantity: " + quantity,
            "Confirm Deletion",
            javax.swing.JOptionPane.YES_NO_OPTION,
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        
        if (option == javax.swing.JOptionPane.YES_OPTION) {
            // Perform deletion (in a real app, this would delete from database)
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Product '" + name + "' has been successfully deleted!",
                "Deletion Successful",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
            );
            
            // Clear the fields after deletion
            txtProname.setText("");
            txtProprice.setText("");
            txtProquantity.setText("");
        }
    }

