 private void handleGoButton() {
        String selectedOption = (String)cboNoo.getSelectedItem();
        String message = "";
        
        switch(selectedOption) {
            case "1":
                message = "Add Product option selected!";
                break;
            case "2":
                message = "View Products option selected!";
                break;
            case "3":
                message = "Update Product Price option selected!";
                break;
            case "4":
                message = "Delete Product option selected!";
                break;
            case "5":
                message = "Returning to Main Menu...";
                break;
            default:
                message = "Please select a valid option!";
        }
        
        JOptionPane.showMessageDialog(this, 
            message, 
            "Option " + selectedOption + " Selected", 
            JOptionPane.INFORMATION_MESSAGE);
    }
