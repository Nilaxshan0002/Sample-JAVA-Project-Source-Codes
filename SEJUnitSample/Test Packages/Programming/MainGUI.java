     private void btnGoActionPerformed(java.awt.event.ActionEvent evt) {
        String selectedOption = cboNo.getSelectedItem().toString();
        
        switch(selectedOption) {
            case "1":
                // Open Admin Login
                JOptionPane.showMessageDialog(this, "Opening Admin Login...");
                // Here you would typically open a new AdminLogin window
                // new AdminLogin().setVisible(true);
                break;
            case "2":
                // Open Customer Login
                JOptionPane.showMessageDialog(this, "Opening Customer Login...");
                // Here you would typically open a new CustomerLogin window
                // new CustomerLogin().setVisible(true);
                break;
            case "3":
                // Exit the application
                JOptionPane.showMessageDialog(this, "Exiting application...");
                System.exit(0);
                break;
            default:
                JOptionPane.showMessageDialog(this, "Please select a valid option!");
                break;
        }
    }
    
    private void btnClearActionPerformed(java.awt.event.ActionEvent evt) {
        // Reset the combo box to default (empty) selection
        cboNo.setSelectedIndex(3); // Index 3 is the empty option in your combo box
    }

