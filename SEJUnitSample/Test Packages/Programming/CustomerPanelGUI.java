    private void handleGoButton() {
        String selectedOption = (String)cboNo.getSelectedItem();
        String message = "";
        
        switch(selectedOption) {
            case "1":
                message = "Browse Products option selected!\nWould display available products here.";
                break;
            case "2":
                message = "Add Product to Order option selected!\nWould add selected product to cart.";
                break;
            case "3":
                message = "View Current Order option selected!\nWould show items in your cart.";
                break;
            case "4":
                message = "Finalize Order option selected!\nWould proceed to checkout.";
                break;
            case "5":
                message = "Returning to Main Menu...";
                break;
            default:
                message = "Please select a valid option!";
        }
        
        JOptionPane.showMessageDialog(this, 
            message, 
            "Option " + selectedOption + " Selected", 
            JOptionPane.INFORMATION_MESSAGE);
    }
