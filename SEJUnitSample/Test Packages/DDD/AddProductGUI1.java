    private void handleAddProduct() {
        String productName = txtpn.getText().trim();
        String priceStr = txtpp.getText().trim();
        String quantityStr = txtpq.getText().trim();
        
        // Validate inputs
        if (productName.isEmpty() || priceStr.isEmpty() || quantityStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Please fill in all product details", 
                "Error", 
                JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        try {
            double price = Double.parseDouble(priceStr);
            int quantity = Integer.parseInt(quantityStr);
            
            if (price <= 0 || quantity <= 0) {
                JOptionPane.showMessageDialog(this, 
                    "Price and quantity must be positive numbers", 
                    "Error", 
                    JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            // Show success message with product details
            JOptionPane.showMessageDialog(this, 
                "Product Added Successfully!\n\n" +
                "Name: " + productName + "\n" +
                "Price: LKR " + price + "\n" +
                "Quantity: " + quantity,
                "Success", 
                JOptionPane.INFORMATION_MESSAGE);
            
            // Here you would typically:
            // 1. Add the product to your database
            // 2. Clear the form or close the window
            // 3. Maybe return to product list
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, 
                "Please enter valid numbers for price and quantity", 
                "Error", 
                JOptionPane.ERROR_MESSAGE);
        }
    }
