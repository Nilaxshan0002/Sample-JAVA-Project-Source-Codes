     private void handleGoButton() {
        String selectedOption = (String) cbo123.getSelectedItem();
        
        switch(selectedOption) {
            case "1":
                JOptionPane.showMessageDialog(this, 
                    "Admin Login Selected - Redirecting to Admin Panel", 
                    "Information", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new AdminPanel().setVisible(true);
                break;
                
            case "2":
                JOptionPane.showMessageDialog(this, 
                    "Customer Login Selected - Redirecting to Customer Panel", 
                    "Information", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new CustomerPanel().setVisible(true);
                break;
                
            case "3":
                int confirm = JOptionPane.showConfirmDialog(this, 
                    "Are you sure you want to exit?", 
                    "Confirm Exit", 
                    JOptionPane.YES_NO_OPTION);
                if (confirm == JOptionPane.YES_OPTION) {
                    System.exit(0);
                }
                break;
        }
    }

    private void handleClearButton() {
        cbo123.setSelectedIndex(0); // Reset to first option
    }
