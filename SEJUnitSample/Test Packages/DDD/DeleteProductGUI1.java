     private void handleDeleteProduct() {
        String productName = txteepn.getText();
        String productPrice = txteepp.getText();
        String productQuantity = txteepq.getText();
        
        if (productName.isEmpty() || productPrice.isEmpty() || productQuantity.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Please fill in all product details", 
                "Error", 
                JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Confirm deletion with user
        int confirm = JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to delete this product?\n\n" +
            "Product: " + productName + "\n" +
            "Price: LKR " + productPrice + "\n" +
            "Quantity: " + productQuantity,
            "Confirm Deletion",
            JOptionPane.YES_NO_OPTION);
        
        if (confirm == JOptionPane.YES_OPTION) {
            // Here you would typically:
            // 1. Delete the product from your database
            // 2. Clear the form or close the window
            // 3. Show success message
            
            JOptionPane.showMessageDialog(this, 
                "Product deleted successfully!\n\n" +
                "Deleted Product: " + productName + "\n" +
                "Price: LKR " + productPrice + "\n" +
                "Quantity: " + productQuantity,
                "Deletion Complete",
                JOptionPane.INFORMATION_MESSAGE);
            
            // Clear the form after deletion
            txteepn.setText("");
            txteepp.setText("");
            txteepq.setText("");
        }
    }
