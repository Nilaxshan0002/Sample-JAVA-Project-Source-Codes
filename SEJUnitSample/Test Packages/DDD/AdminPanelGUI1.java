    private void handleGoButton() {
        String selectedOption = (String) cbo1.getSelectedItem();
        
        switch(selectedOption) {
            case "1":
                JOptionPane.showMessageDialog(this, 
                    "Add Product Selected - Opening Add Product Form", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new AddProductGUI().setVisible(true);
                break;
                
            case "2":
                JOptionPane.showMessageDialog(this, 
                    "View Products Selected - Opening Products List", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new ViewProductsGUI().setVisible(true);
                break;
                
            case "3":
                JOptionPane.showMessageDialog(this, 
                    "Update Product Price Selected - Opening Price Update Form", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new UpdatePriceGUI().setVisible(true);
                break;
                
            case "4":
                JOptionPane.showMessageDialog(this, 
                    "Delete Product Selected - Opening Delete Product Form", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new DeleteProductGUI().setVisible(true);
                break;
                
            case "5":
                int confirm = JOptionPane.showConfirmDialog(this, 
                    "Return to Main Menu?", 
                    "Confirm Navigation", 
                    JOptionPane.YES_NO_OPTION);
                if (confirm == JOptionPane.YES_OPTION) {
                    this.dispose(); // Close current window
                    // Here you would add: new MainGUI().setVisible(true);
                }
                break;
                
            default:
                JOptionPane.showMessageDialog(this, 
                    "Please select a valid option", 
                    "Error", 
                    JOptionPane.ERROR_MESSAGE);
        }
    }

    private void handleClearButton() {
        cbo1.setSelectedIndex(0); // Reset to first option
    }
