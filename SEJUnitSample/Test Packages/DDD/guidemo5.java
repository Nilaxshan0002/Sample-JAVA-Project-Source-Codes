    private void tableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tableMouseClicked
         int rowId = table.getSelectedRow();
        
        String Product_Id= dtm.getValueAt(rowId, 0).toString();
        String Product_name = dtm.getValueAt(rowId, 1).toString();
        String UnitPrice = dtm.getValueAt(rowId, 2).toString();
        String Quantity = dtm.getValueAt(rowId, 3).toString();
        String Category = dtm.getValueAt(rowId, 4).toString();
        
        
        txtproductid.setText(Product_Id);
        txtproductname.setText(Product_name);
        txtunitprice.setText(UnitPrice);
        txtquantity.setText(Quantity);
        txtcategory.setText(Category);
        
    }//GEN-LAST:event_tableMouseClicked

