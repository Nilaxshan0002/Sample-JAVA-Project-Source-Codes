    private void handleGoButton() {
        String selectedOption = (String) cbo12.getSelectedItem();
        
        switch(selectedOption) {
            case "1":
                JOptionPane.showMessageDialog(this, 
                    "Browse Products Selected", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new BrowseProductsGUI().setVisible(true);
                break;
                
            case "2":
                JOptionPane.showMessageDialog(this, 
                    "Add Product to Order Selected", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new AddProductGUI().setVisible(true);
                break;
                
            case "3":
                JOptionPane.showMessageDialog(this, 
                    "View Current Order Selected", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new ViewOrderGUI().setVisible(true);
                break;
                
            case "4":
                JOptionPane.showMessageDialog(this, 
                    "Finalize Order Selected", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                // Here you would add: new FinalizeOrderGUI().setVisible(true);
                break;
                
            case "5":
                JOptionPane.showMessageDialog(this, 
                    "Returning to Main Menu", 
                    "Option Selected", 
                    JOptionPane.INFORMATION_MESSAGE);
                this.dispose(); // Close current window
                // Here you would add: new MainGUI().setVisible(true);
                break;
                
            default:
                JOptionPane.showMessageDialog(this, 
                    "Please select a valid option", 
                    "Error", 
                    JOptionPane.ERROR_MESSAGE);
        }
    }

    private void handleClearButton() {
        cbo12.setSelectedIndex(0); // Reset to first option
    }
