    private void handleLogin() {
        String username = txteu.getText().trim();
        String password = new String(((javax.swing.JPasswordField)txtep).getPassword()).trim();
        
        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Please enter both username and password", 
                "Login Error", 
                JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (username.equals(ADMIN_USERNAME)) {
            if (password.equals(ADMIN_PASSWORD)) {
                // Successful login
                JOptionPane.showMessageDialog(this, 
                    "Admin Login Successful! Welcome " + username, 
                    "Success", 
                    JOptionPane.INFORMATION_MESSAGE);
                
                // Open admin panel and close login window
                this.dispose();
                new AdminPanelGUI1().setVisible(true);
            } else {
                JOptionPane.showMessageDialog(this, 
                    "Incorrect admin password", 
                    "Login Failed", 
                    JOptionPane.ERROR_MESSAGE);
            }
        } else {
            JOptionPane.showMessageDialog(this, 
                "Invalid admin username", 
                "Login Failed", 
                JOptionPane.ERROR_MESSAGE);
        }
    }

